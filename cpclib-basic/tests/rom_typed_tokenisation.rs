/// A `:` ends a DATA only outside quotes.
#[test]
fn data_ends_at_a_colon_outside_quotes() {
    let program = cpclib_basic::BasicProgram::parse("10 DATA \"A:B\",2:PRINT 1\n").unwrap();
    let bytes = program.as_bytes();
    let data = &bytes[4..];
    assert_eq!(&data[..10], &[0x8c, 0x20, 0x22, 0x41, 0x3a, 0x42, 0x22, 0x2c, 0x32, 0x01]);
    assert_eq!(&data[10..13], &[0xbf, 0x20, 0x0f], "PRINT 1 after the DATA");
}

