//! Byte-exact tokenisation against the Locomotive BASIC ROM itself.
//!
//! Each expected program is what BASIC 1.1 stored after the line was typed
//! on a booted CPC 6128 - the ROM's own tokeniser, run by a pin-level
//! emulator (bemu), read back from &0170. BASIC 1.0 (464) and the 664's 1.1
//! give the same bytes for every line here (bar `GRAPHICS`, which 1.0 does
//! not have). Unlike the re-saved fixtures of `real_cpc_tokenisation.rs`,
//! every line here was tokenised from its text by the ROM: no byte is a
//! previous version of this crate's own output.
//!
//! What they show: a decimal literal is encoded the same way wherever it
//! appears - assignment, command or function argument - `0`-`9` as one
//! byte (&0E-&17), `10`-`255` as &19 nn, up to `32767` as &1A nnnn, larger
//! values as a float; DATA keeps its items as typed; `ON ERROR GOTO`,
//! `ON BREAK` and bare `RND` have their own tokens.

fn assert_rom_tokenisation(line: &str, rom: &[u8]) {
    let ours = cpclib_basic::BasicProgram::parse(format!("{line}\n"))
        .unwrap_or_else(|e| panic!("{line}: {e}"))
        .as_bytes();
    assert_eq!(ours, rom, "{line}\nours: {ours:02X?}\nrom:  {rom:02X?}");
}

macro_rules! rom_cases {
    ($($name:ident: $line:expr => [$($byte:expr),*];)*) => {$(
        #[test]
        fn $name() {
            assert_rom_tokenisation($line, &[$($byte),*]);
        }
    )*};
}

